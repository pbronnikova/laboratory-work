def set_plain_text(paragraph, text: str) -> None:
    if paragraph.runs:
        paragraph.runs[0].text = text
        for r in paragraph.runs[1:]:
            r.text = ""
    else:
        paragraph.add_run(text)


def is_command_line(text: str) -> bool:
    t = text.strip()
    return t.startswith("$ git") or (t.startswith("$") and "git" in t)


def apply_command_font(paragraph) -> None:
    for run in paragraph.runs:
        run.font.name = "Courier New"
        run.font.size = Pt(11)


def should_indent(i: int, style_name: str, text: str) -> bool:
    if not text.strip():
        return False
    # Title page + toc header
    if i < 48:
        return False
    if style_name.startswith("Heading"):
        return False
    # Figure captions and short pseudo-headings inside section 1 — still body text
    if text.strip() in ("Оглавление",):
        return False
    return True


def main() -> None:
    doc = Document(SRC)

    for i, p in enumerate(doc.paragraphs):
        style_name = p.style.name if p.style else "Normal"
        if i in PARA_TEXT:
            set_plain_text(p, PARA_TEXT[i])
        else:
            # Global spelling fixes in unchanged paragraphs
            t = p.text
            t = t.replace("Github", "GitHub").replace("GIT", "Git")
            t = t.replace("репозитария", "репозитория").replace("репозитарий", "репозиторий")
            t = t.replace("репозитариям", "репозиториям").replace("репозитарию", "репозиторию")
            if t != p.text:
                set_plain_text(p, t)

        final_text = p.text
        if is_command_line(final_text):
            apply_command_font(p)

        if should_indent(i, style_name, final_text):
            p.paragraph_format.first_line_indent = Cm(1.25)
            p.paragraph_format.alignment = WD_PARAGRAPH_ALIGNMENT.JUSTIFY

    doc.save(OUT)
    print("Saved:", OUT)


if __name__ == "__main__":
    main()
